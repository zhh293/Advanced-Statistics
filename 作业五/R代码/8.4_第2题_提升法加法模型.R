# 论证：当提升法（boosting）的每棵树都是"树桩"（depth=1, 即只有一次分裂）时，
# 每棵树只依赖单个预测变量 X_j，形如 f^b(X) = c * I(X_j < t) 或常数偏移。
#
# 提升法的更新规则： f(x) <- f(x) + λ * f^b(x)
# 累加 B 棵树后： f(X) = Σ_{b=1}^{B} λ * f^b(X)
#
# 由于每棵树桩只用到一个变量 X_{j(b)}，把所有用到同一变量 X_j 的树桩归并，
# 得到一个只关于 X_j 的函数 f_j(X_j)：
#
#         f(X) = Σ_{j=1}^{p} f_j(X_j)        ……(8.12)
#
# 这正是一个加法模型（additive model）的形式：
# 整体函数是各单变量函数之和，不含变量间的交互项。
# 这说明 interaction.depth=1 的提升法等价于拟合一个加法模型。
