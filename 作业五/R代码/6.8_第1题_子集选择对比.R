# 第1题：最优子集选择 vs 向前逐步 vs 向后逐步选择（概念题）
# 高级统计方法 第5次作业
# 张鸿昊 20242081353
#
# 本题为概念题，无需编程，结论如下：
#
# (a) 含k个变量的三个模型中，训练RSS最小的是【最优子集选择】。
#     因为最优子集选择在所有C(p,k)个k变量组合中穷举搜索、选训练RSS最小者；
#     而逐步法只在受限的路径上搜索，找到的不一定是全局最优。
#
# (b) 测试RSS最小的【不确定是哪一个】。训练RSS小不代表测试RSS小，
#     最优子集选择可能过拟合训练集，逐步法选出的模型在测试集上有可能更好。
#
# (c) 真假判断：
#     i.   真。向前逐步k变量模型的预测变量是k+1变量模型的子集（嵌套）。
#     ii.  真。向后逐步k变量模型的预测变量是k+1变量模型的子集（嵌套）。
#     iii. 假。向后逐步的k变量模型不一定是向前逐步k+1变量模型的子集。
#     iv.  假。向前逐步的k变量模型不一定是向后逐步k+1变量模型的子集。
#     v.   假。最优子集选择的k变量模型不一定是其(k+1)变量模型的子集（无嵌套约束）。
