# 题目背景：研究者对某组织样本测了1000个基因的表达，共100个样本
#   (前50个来自对照组，后50个来自处理组)。对数据做PCA后发现：
#   第一主成分(PC1)解释了10%的方差。研究者怀疑实验在两个不同时间(机器)采集，
#   想检验"采集批次"是否是 PC1 的主要来源。
#
# (a) 研究者建议：在做PCA前，给每个样本的基因表达都加上一个常数(取决于该样本
#     是哪台机器采的)。请说明这样做是否合理。
#   答：不合理。对某个样本的【所有基因】同时加同一常数，相当于平移该样本向量，
#       PCA通常会先对每个基因(变量)做中心化(减均值)，逐变量中心化后，
#       "整条样本统一加常数"并不能干净地表示批次效应——批次效应一般体现为
#       不同基因受影响程度不同。更稳妥的做法见(b)。
#
# (b) 更好的做法：把"机器/批次"作为一个额外特征(协变量)加入分析，
#     或在PCA前先对每个基因做批次校正(如减去各批次该基因的均值)。
#     这样能显式建模批次效应，再看PC1是否仍由批次驱动。
#
# (c) 本脚本用模拟数据演示：当确实存在批次效应时，PC1会与批次高度相关；
#     做批次校正(每个基因减去其批次均值)后，PC1不再由批次主导。

set.seed(6)
n <- 100; p <- 1000
# 真实信号弱 + 批次效应：前50与后50在部分基因上有系统偏移
batch <- rep(c("机器A", "机器B"), each = 50)
X <- matrix(rnorm(n * p), nrow = n)
# 给机器B的前200个基因加一个批次偏移(各基因偏移不同)
shift <- rnorm(200, mean = 1.5, sd = 0.3)
X[batch == "机器B", 1:200] <- X[batch == "机器B", 1:200] +
  matrix(shift, nrow = 50, ncol = 200, byrow = TRUE)

# ---- 未校正：PCA ----
pc.raw <- prcomp(X, scale. = TRUE)
pc1.raw <- pc.raw$x[, 1]
cat("=== 未做批次校正 ===\n")
cat("PC1 与批次的关联(按批次的PC1均值):\n")
print(tapply(pc1.raw, batch, mean))
cat("批次对PC1的方差解释 R^2 =",
    round(summary(lm(pc1.raw ~ batch))$r.squared, 3), "（接近1说明PC1由批次主导）\n\n")

# ---- 批次校正：每个基因减去其所在批次的均值 ----
Xc <- X
for (b in unique(batch)) {
  idx <- batch == b
  Xc[idx, ] <- sweep(X[idx, ], 2, colMeans(X[idx, ]))
}
pc.adj <- prcomp(Xc, scale. = TRUE)
pc1.adj <- pc.adj$x[, 1]
cat("=== 批次校正后 ===\n")
cat("批次对PC1的方差解释 R^2 =",
    round(summary(lm(pc1.adj ~ batch))$r.squared, 3), "（接近0说明已去除批次影响）\n")
