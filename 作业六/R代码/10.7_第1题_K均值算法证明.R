# (a) 证明等式 (10.12)：
#     (1/|C_k|) * Σ_{i,i'∈C_k} Σ_j (x_ij - x_i'j)^2
#       = 2 * Σ_{i∈C_k} Σ_j (x_ij - xbar_kj)^2
#     其中 xbar_kj 是第k类在第j个特征上的均值。
#   证明思路：对每个特征j，利用方差恒等式
#     Σ_{i,i'}(x_i - x_i')^2 = 2|C_k| Σ_i (x_i - xbar)^2
#   （两两差平方和 = 2*样本量*与均值离差平方和），
#   两边除以 |C_k| 即得 (10.12)。
#
# (b) (10.12)说明：K均值的目标(10.11)是"类内两两距离平方和/|C_k|"，
#     等于"2倍的类内离差平方和(到类中心)"。算法10.1每次迭代：
#     第1步把每个观测分配到最近的类中心，第2步重新计算类中心为均值。
#     由于均值是使离差平方和最小的点，每一步都不会增大(10.11)的目标值，
#     因此目标式单调下降，算法收敛到一个局部最优。

# ====== 数值验证等式(10.12) ======
set.seed(1)
Ck <- matrix(rnorm(20), ncol = 2)   # 某一类的10个观测，2个特征
m <- nrow(Ck)

# 左式：(1/|Ck|) * 所有两两差平方和
lhs <- 0
for (i in 1:m) for (ii in 1:m) lhs <- lhs + sum((Ck[i, ] - Ck[ii, ])^2)
lhs <- lhs / m

# 右式：2 * 到类中心(均值)的离差平方和
center <- colMeans(Ck)
rhs <- 2 * sum(sweep(Ck, 2, center)^2)

cat("等式(10.12) 左式 =", round(lhs, 6), "\n")
cat("等式(10.12) 右式 =", round(rhs, 6), "\n")
cat("两者相等:", isTRUE(all.equal(lhs, rhs)), "\n")
cat("\n这验证了(10.12)：类内两两距离平方和(除以|Ck|)等于2倍的类内离差平方和。\n")
