# 题目背景：图中给出8位购物者对若干商品的购买数量，对其作 K=2 的 K均值聚类。
#   要讨论三种不同的数据预处理方式会得到什么样的聚类结果：
#   (1) 直接对原始购买数量聚类；
#   (2) 把每个变量标准化(标准差为1)后再聚类；
#   (3) 把购买数量换成"是否购买(0/1)"后再聚类。
#
# 讨论结论：
#   (1) 原始数量：聚类被【数量级大的商品】主导。例如某商品销量动辄上千，
#       另一些只有个位数，则距离几乎完全由大销量商品决定，
#       聚类结果反映的是"买大件商品多 vs 少"。
#   (2) 标准化后：每个变量贡献被拉平到同一尺度，
#       聚类同时考虑所有商品，结果更均衡、更能反映整体购买模式差异。
#   (3) 二值化(买/不买)：忽略购买数量，只看购买种类的组合，
#       聚类反映的是"购买的商品类别结构"是否相似，而非购买强度。
# 因此预处理方式不同，聚类的业务含义截然不同，应根据分析目标选择。

# ====== 数值演示：构造一份模拟购买数据 ======
set.seed(5)
# 8个购物者(行)，4种商品(列)：商品4数量级远大于其他
shoppers <- data.frame(
  面包 = c(2, 3, 1, 0, 2, 1, 0, 3),
  牛奶 = c(1, 0, 2, 3, 1, 0, 2, 1),
  鸡蛋 = c(0, 1, 1, 2, 0, 1, 2, 0),
  矿泉水 = c(300, 50, 280, 40, 320, 60, 30, 290)   # 数量级大
)
rownames(shoppers) <- paste0("顾客", 1:8)

# (1) 原始数量聚类
set.seed(1); km1 <- kmeans(shoppers, centers = 2, nstart = 20)
# (2) 标准化后聚类
set.seed(1); km2 <- kmeans(scale(shoppers), centers = 2, nstart = 20)
# (3) 二值化(>0记为1)后聚类
bin <- as.data.frame(ifelse(shoppers > 0, 1, 0))
set.seed(1); km3 <- kmeans(bin, centers = 2, nstart = 20)

cat("=== (1) 原始数量聚类（被矿泉水主导）===\n"); print(km1$cluster)
cat("\n=== (2) 标准化后聚类（各商品权重均衡）===\n"); print(km2$cluster)
cat("\n=== (3) 二值化后聚类（只看是否购买）===\n"); print(km3$cluster)
cat("\n可见三种预处理给出不同的分组，说明预处理方式显著影响聚类结果。\n")
