#
# 题目：假设有一组观测，分别用最长距离法(complete)和最短距离法(single)
#       进行系统聚类。
#
# (a) 在某个高度上，类{1,2}与类{4,5}发生汇合。用最长距离法时它们汇合的高度，
#     与用最短距离法时相比，谁高谁低，还是无法确定？
#   答：无法确定一定谁高，但通常"最长距离法 >= 最短距离法"。
#       因为同一对类之间：
#         complete 的汇合高度 = 两类间观测对的【最大】相异度
#         single   的汇合高度 = 两类间观测对的【最小】相异度
#       最大值 >= 最小值，所以 complete 的汇合高度 >= single 的汇合高度。
#       只有当两类间所有观测对相异度都相等时，两者才相等。
#
# (b) 在某个高度上，类{5}与类{6}发生汇合（都是单点类）。此时两种方法的
#     汇合高度相比，谁高谁低，还是无法确定？
#   答：二者相等。因为单点类之间只有唯一一对观测(5,6)，
#       此时"最大相异度"="最小相异度"=d(5,6)，
#       complete 与 single 给出完全相同的汇合高度。

# ====== 数值演示：验证 (a) complete >= single ======
set.seed(10)
X <- matrix(rnorm(12 * 2), ncol = 2)            # 12个观测、2特征
D <- as.matrix(dist(X))

# 任取两类 A={1,2}, B={4,5}，比较其间最大/最小相异度
A <- c(1, 2); B <- c(4, 5)
between <- D[A, B]
cat("=== (a) 类{1,2}与{4,5}之间的相异度矩阵 ===\n")
print(round(between, 3))
cat("最短距离法(single)汇合高度 = 最小值 =", round(min(between), 3), "\n")
cat("最长距离法(complete)汇合高度 = 最大值 =", round(max(between), 3), "\n")
cat("=> complete >= single：", max(between) >= min(between), "\n\n")

# ====== 验证 (b) 单点类相等 ======
cat("=== (b) 单点类{5}与{6}汇合 ===\n")
cat("d(5,6) =", round(D[5, 6], 3), "（complete 与 single 完全相同）\n")
cat("=> 两种方法汇合高度相等\n")
